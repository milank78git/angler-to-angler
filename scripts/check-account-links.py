"""Validate the public Android association and fallback before enabling HTTPS email links."""
import argparse
import json
import re
import sys
import urllib.error
import urllib.request
from pathlib import Path

PACKAGE = 'app.anglers.journal'
RELATION = 'delegate_permission/common.handle_all_urls'


class NoRedirect(urllib.request.HTTPRedirectHandler):
    def redirect_request(self, *args):
        return None


def fetch(url):
    request = urllib.request.Request(url, headers={'User-Agent': 'Angler-App-Link-Check/1'})
    with urllib.request.build_opener(NoRedirect()).open(request, timeout=12) as response:
        body = response.read(1024 * 1024 + 1)
        if len(body) > 1024 * 1024:
            raise ValueError('response exceeds 1 MiB')
        return response.status, response.headers, body


def check(host, bundle, get=fetch):
    if len(host) > 253 or '.' not in host or not all(
        re.fullmatch(r'[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?', part) for part in host.split('.')
    ):
        raise ValueError('Expected a DNS hostname')
    expected = json.loads((bundle / '.well-known/assetlinks.json').read_bytes())
    missing = set(expected[0]['target']['sha256_cert_fingerprints'])
    origin = 'https://' + host

    def document(path, mime):
        try:
            status, headers, body = get(origin + path)
        except urllib.error.HTTPError as err:
            raise ValueError(f'{path} returned HTTP {err.code}; direct HTTP 200 required') from None
        if status != 200 or headers.get_content_type() != mime:
            raise ValueError(f'{path} must return HTTP 200 with {mime}')
        return headers, body

    _, body = document('/.well-known/assetlinks.json', 'application/json')
    statements = json.loads(body)
    if not isinstance(statements, list):
        raise ValueError('assetlinks.json must contain an array of statements')
    for statement in statements:
        if not isinstance(statement, dict):
            continue
        target = statement.get('target')
        if not isinstance(target, dict) or target.get('namespace') != 'android_app' or target.get('package_name') != PACKAGE:
            continue
        relations = statement.get('relation')
        certs = target.get('sha256_cert_fingerprints')
        if isinstance(relations, list) and RELATION in relations and isinstance(certs, list):
            missing.difference_update(cert.upper() for cert in certs if isinstance(cert, str))
    if missing:
        raise ValueError('assetlinks.json does not delegate app links to the pilot package and signing certificate')

    headers, body = document(f'/account/{PACKAGE}/callback', 'text/html')
    directives = {item.strip().lower() for item in headers.get('Cache-Control', '').split(',')}
    if 'no-store' not in directives or headers.get('Referrer-Policy', '').strip().lower() != 'no-referrer':
        raise ValueError('Callback must return Cache-Control: no-store and Referrer-Policy: no-referrer')
    if not all(mark in body for mark in (
        b'<title>Angler to Angler</title>', b'<section lang="en">', b'<section lang="cs">', b'info@horistum.com'
    )):
        raise ValueError('Expected the account help page at the exact callback path')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('host')
    parser.add_argument('bundle', type=Path, help='Directory generated by build-account-links.py')
    args = parser.parse_args()
    try:
        check(args.host, args.bundle)
    except (ValueError, OSError) as error:
        sys.exit(f'Account link check failed for {args.host}: {error}')
    print(f'Android association and account fallback passed for {args.host}.')
