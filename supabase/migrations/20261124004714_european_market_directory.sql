alter function angler_market.publish(uuid,integer,jsonb) rename to publish_validated_draft;
revoke all on function angler_market.publish_validated_draft(uuid,integer,jsonb) from public,anon,authenticated;
create function angler_market.publish(offer_id uuid, expected_revision integer, draft jsonb) returns jsonb
language plpgsql security definer set search_path='' as $$
declare actor uuid:=angler_groups_private.subject(); name text:=btrim(draft->>'species'); species_key text;
begin
 select latin into species_key from angler_market.species where latin=name;
 if species_key is null then select latin into species_key from angler_market.species_alias where alias=lower(name); end if;
 if species_key is null then
   -- Accept an unchanged legacy label solely on a revision already owned by this seller.
   if not exists(select from angler_market.offers o join angler_market.versions v on v.offer=o.id and v.revision=o.revision
      where o.id=offer_id and o.seller=actor and v.species=name)
   then raise exception 'Choose a catalogue species' using errcode='PT422'; end if;
   species_key:=name;
 end if;
 return angler_market.publish_validated_draft(offer_id,expected_revision,jsonb_set(draft,'{species}',to_jsonb(species_key)));
end$$;
revoke all on function angler_market.publish(uuid,integer,jsonb) from public,anon,authenticated;
grant execute on function angler_market.publish(uuid,integer,jsonb) to authenticated;
create or replace function public.angler_market_publish(offer_id uuid, expected_revision integer, draft jsonb)
returns jsonb language sql security invoker set search_path='' as $$ select angler_market.publish(offer_id,expected_revision,draft) $$;

-- Ratings follow a tip across revisions. An arithmetic mean of the three scores gives each purchase equal weight.
create or replace function angler_market.preview(o angler_market.offers, v angler_market.versions) returns jsonb
language sql stable set search_path='' as $$
 select jsonb_build_object('id',o.id,'revision',v.revision,'title',v.title,'species',v.species,'day',v.trip_day,
   'access',v.access,'water',v.water,'price',v.price,'limit',v.sale_limit,'sold',o.sold,'withdrawn',o.withdrawn,
   'offerRating',(select jsonb_build_object('count',count(*),'average',round(avg(r.rating_accuracy+r.rating_technique+r.rating_match)/3,1))
                  from angler_market.orders r where r.offer=o.id and r.rating_accuracy is not null),
   'authorRating',angler_market.author_rating(o.seller),
   'author',(select display_name from angler_private.profiles where user_id=o.seller))
$$;
-- Count all available offers under the filter before paginating. No technique text enters this projection.
create function angler_market.discover(water_key text, before_position bigint) returns jsonb
language plpgsql stable security definer set search_path='' as $$
declare actor uuid:=angler_groups_private.subject();
begin
 return (with live as materialized (
   select o.id,o.position,o.seller,o.sold,o.revision
   from angler_market.offers o join angler_market.versions v on (v.offer,v.revision)=(o.id,o.revision)
   where not o.withdrawn and (v.sale_limit is null or o.sold<v.sale_limit) and (water_key is null or v.water=water_key)),
 batch as (select * from live where before_position is null or position<before_position order by position desc limit 21),
 shown as (select * from batch order by position desc limit 20)
 select jsonb_build_object('items',coalesce((select jsonb_agg(angler_market.preview(o,v) order by s.position desc)
  from shown s join angler_market.offers o on o.id=s.id join angler_market.versions v on (v.offer,v.revision)=(s.id,s.revision)),'[]'::jsonb),
  'balance',(select balance from angler_market.wallets where holder=actor),
  'next',case when (select count(*) from batch)>20 then (select min(position)::text from shown) end,
  'stats',jsonb_build_object('offers',count(*),'authors',count(distinct seller),'sales',coalesce(sum(sold),0),
    'ratings',(select count(*) from angler_market.orders r join live l on l.id=r.offer where r.rating_accuracy is not null))) from live);
end$$;
create function public.angler_market_discover(water_key text default null,before_position bigint default null)
returns jsonb language sql security invoker set search_path='' as $$ select angler_market.discover(water_key,before_position) $$;
revoke all on function angler_market.discover(text,bigint),public.angler_market_discover(text,bigint) from public,anon,authenticated;
grant execute on function angler_market.discover(text,bigint),public.angler_market_discover(text,bigint) to authenticated;
